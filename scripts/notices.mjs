// Writes THIRD-PARTY-NOTICES.md: every npm package an install of ask-kit pulls in (the
// production dependency tree), with its licence text.
// usage: node scripts/notices.mjs > THIRD-PARTY-NOTICES.md   (after npm ci)
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const dirs = execFileSync(npm, ["ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8", shell: process.platform === "win32" })
  .split(/\r?\n/)
  .filter((d) => d && d.includes("node_modules"));

const entries = [];
for (const full of dirs) {
  const pkg = JSON.parse(readFileSync(join(full, "package.json"), "utf8"));
  // The same version installed in more than one place is listed once.
  if (entries.some((e) => e.name === pkg.name && e.version === pkg.version)) continue;
  const file = readdirSync(full).find((f) => /^(licen[cs]e|copying)(\.|$|-)/i.test(f));
  const text = file ? readFileSync(join(full, file), "utf8").replace(/\r\n/g, "\n").trim() : null;
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "unknown";
  const repo = String(pkg.repository?.url ?? pkg.repository ?? "").replace(/^git\+/, "");
  entries.push({ name: pkg.name, version: pkg.version, license, text, repo });
}
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const out = [
  "# Third-party notices",
  "",
  "ask-kit is MIT licensed (see LICENSE). Installing it also installs the npm packages below,",
  "each under its own licence, reproduced here. `@vscode/ripgrep` downloads a ripgrep binary",
  "(https://github.com/BurntSushi/ripgrep, MIT or Unlicense) during install.",
  "",
  "Generated by `node scripts/notices.mjs`.",
  "",
  "## npm packages",
  "",
];
for (const e of entries) {
  out.push(`### ${e.name} ${e.version} (${e.license})`, "");
  if (e.repo) out.push(e.repo, "");
  out.push(e.text ? ["```", e.text, "```"].join("\n") : `Licensed under ${e.license}; the package ships no licence file.`, "");
}
process.stdout.write(`${out.join("\n")}\n`);
