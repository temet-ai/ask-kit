// Explicit result reviews survive output clipping and trajectory settings, on shots and asks.
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { fakeBackend } from "./fixtures/shot-kit/fake-backend.mjs";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "ask-review-"));
const config = path.join(tmp, "config");
const state = path.join(tmp, "state");
process.env.ASK_KIT_CONFIG = config;
process.env.ASK_KIT_STATE = state;
const kit = path.join(config, "kits", "watch");
fs.cpSync(path.join(ROOT, "test", "fixtures", "shot-kit"), kit, { recursive: true });
fs.writeFileSync(path.join(kit, "scripts", "badge.mjs"), `export const meta = { purpose: "make a Watch badge", params: {}, returns: "a badge with a review" };\nexport default async (_, { status = "needs_review" } = {}) => ({ detail: "x".repeat(10000), review: { status, warnings: Array(20).fill("Wrong size: " + "x".repeat(500)), notes: "The Watch badge has the wrong dimensions.", privateField: "not a review field" } });\n`);
const fake = await fakeBackend([{ code: 'await scripts.run("badge")' }, { answer: "The badge is saved but its dimensions need review." }]);
fs.writeFileSync(path.join(config, "config.json"), JSON.stringify({ version: 1, sources: [], backends: { default: "fake", list: { fake: fake.backend } }, domains: { watch: {} } }));
const env = { ...process.env, ASK_KIT_CONFIG: config, ASK_KIT_STATE: state, ASK_KIT_SESSION: "vimes", ASK_KIT_DOMAIN: "watch" };
const client = new Client({ name: "test", version: "0" });
await client.connect(new StdioClientTransport({ command: process.execPath, args: [path.join(ROOT, "src", "server.mjs")], env, stderr: "inherit" }));
const shot = await client.callTool({ name: "ask", arguments: { do: "badge" } });
assert.ok(!shot.isError, "a result review does not pretend execution failed");
const first = JSON.parse(fs.readFileSync(path.join(state, "watch", "vimes.jsonl"), "utf8").trim());
assert.equal(first.ok, true);
assert.equal(first.reviews[0].status, "needs_review");
assert.equal(first.reviews[0].warnings.length, 8);
assert.equal(first.reviews[0].warnings[0].length, 300);
assert.equal(first.reviews[0].privateField, undefined);
assert.equal(first.answer, undefined, "trajectories remain off");
assert.equal(fake.requests.length, 0, "a shot never calls the model");
await client.callTool({ name: "ask", arguments: { do: "badge", params: { status: "pass" } } });
await client.callTool({ name: "ask", arguments: { do: "duty" } });
const model = await client.callTool({ name: "ask", arguments: { question: "make a Watch badge", early: false } });
assert.ok(!model.isError);
assert.equal(fake.requests.length, 2);
await client.close();
const rows = fs.readFileSync(path.join(state, "watch", "vimes.jsonl"), "utf8").trim().split("\n").map(JSON.parse);
const cell = JSON.parse(fs.readFileSync(path.join(state, "watch", `ask-${rows[3].askId}.jsonl`), "utf8").trim());
assert.equal(cell.caller, "vimes");
assert.equal(cell.scripts[0].review.status, "needs_review");
assert.equal(cell.result, undefined, "full script results are not silently journaled");
const { report } = await import("../src/report.mjs");
let r = report({ kit: "watch", since: "1h", real: true });
assert.equal(r.asks, 4);
assert.equal(rows[1].askId, rows[0].askId, "successive shots share their REPL");
assert.equal(rows[1].reviews[0].status, "pass");
assert.deepEqual(rows[2].reviews, [], "a script with no review records that fact");
for (const a of r.flaggedAsks.filter((a) => a.question === "do watch.duty" || a.ts === rows[1].ts)) assert.ok(!a.signals.some((s) => s.startsWith("review ")), "a passing shot cannot inherit an adjacent result review");
assert.equal(r.flaggedAsks.filter((a) => a.signals.includes("review needs_review")).length, 2, "shot and model ask are both flagged");
assert.equal(r.reviewFindings.length, 2);
execFileSync(process.execPath, [path.join(ROOT, "bin", "ask-kit.mjs"), "run", "watch", "badge", "status=unverified"], { env: { ...env, ASK_KIT_SESSION: "carrot" }, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
r = report({ kit: "watch", since: "1h", real: true });
assert.equal(r.flaggedAsks.filter((a) => a.signals.includes("review unverified")).length, 1, "CLI shots retain unverified verdicts");
const { reviewOf } = await import("../src/review.mjs");
assert.equal(reviewOf({ status: "needs_review" }), null, "only an explicit review object is captured");
assert.equal(reviewOf({ review: { status: "pending" } }), null);
assert.deepEqual(reviewOf({ review: { status: "pass", warnings: [1, {}] } }), { status: "pass" });
await fake.close();
fs.rmSync(tmp, { recursive: true, force: true });
console.log("ok");
process.exit(0);
